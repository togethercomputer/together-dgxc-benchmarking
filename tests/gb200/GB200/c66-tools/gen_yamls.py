#!/usr/bin/env python3
"""Derive cluster-661303b8 (12-node GB200, infra-perf reserved, no Multus/RDMA) YAMLs
from the R01 rack-readiness YAMLs. Text-level transform so ConfigMap scripts stay verbatim."""
import re, sys, pathlib

SRC = pathlib.Path.home() / "together-dgxc-benchmarking/tests/gb200/GB200"
DST = SRC
CLIQUE = "1849c6a7-9009-4917-9e85-66803cbe32df.32766"
OLD_CLIQUE = "4efdce90-b191-4acc-9a4e-9af0e63d1c46.32766"
NS = "infra-perf"


def common(t: str) -> str:
    # Drop Multus annotations (+ preceding comment lines) and RDMA shared-device resources.
    t = re.sub(r"\n[ \t]*# (Adjust NetworkAttachmentDefinition|Must match the JobSet-level)[^\n]*", "", t)
    t = re.sub(r"\n[ \t]*k8s\.v1\.cni\.cncf\.io/networks:[^\n]*", "", t)
    t = re.sub(r"\n[ \t]*annotations:(?=\n[ \t]*spec:)", "", t)  # now-empty JobSet annotations
    t = re.sub(r"\n[ \t]*rdma/rdma_shared_device_[a-d]:[^\n]*", "", t)
    t = re.sub(r"\n[ \t]*feature\.node\.kubernetes\.io/rdma\.capable:[^\n]*", "", t)
    t = re.sub(r"\n[ \t]*# Adjust to match your InfiniBand HCA[^\n]*", "", t)
    t = re.sub(r"\n[ \t]*- name: NCCL_IB_HCA\n[ \t]*value:[^\n]*", "", t)
    # Reservation: swap together.ai/benchmark toleration for reserved-for=infra-perf.
    t = re.sub(r"\n([ \t]*)# Benchmark reservation:[^\n]*", "", t)
    t = re.sub(r"(\n[ \t]*)- key: together\.ai/benchmark\n[ \t]*operator: Equal\n[ \t]*value: johnson",
               r"\1- key: reserved-for\1  operator: Equal\1  value: infra-perf", t)
    t = re.sub(r"(\n([ \t]*)nvidia\.com/gpu\.present: \"true\")", r"\1\n\2reserved-for: infra-perf", t)
    t = re.sub(r"\n[ \t]*# Replace with your clique ID[^\n]*", "", t)
    t = t.replace(OLD_CLIQUE, CLIQUE)
    # Namespace on every top-level object.
    t = re.sub(r"(\nmetadata:\n)(  name:)", rf"\1  namespace: {NS}\n\2", t)
    assert "rdma_shared" not in t and "cni.cncf" not in t and OLD_CLIQUE not in t
    return t


def sub1(t, old, new, count=0):
    n = t.count(old)
    assert n and (not count or n == count), (old, n)
    return t.replace(old, new)


def nccl():
    t = (SRC / "nccl-18n-r01.yaml").read_text()
    t = common(t)
    t = sub1(t, "nccl-18n-r01", "nccl-12n-c66")
    t = sub1(t, "completions: 18", "completions: 12", 1)
    t = sub1(t, "parallelism: 18", "parallelism: 12", 1)
    t = sub1(t, "N_NODES=18", "N_NODES=12", 1)
    return t


def qwen():
    t = (SRC / "qwen-72b-r01.yaml").read_text()
    t = common(t)
    t = sub1(t, "qwen72b-r01", "qwen72b-c66")
    t = re.sub(r"\A(#[^\n]*\n)+\n?", (
        "# Qwen2.5 72B BF16 on cluster 661303b8 (12-node GB200, infra-perf). 8 nodes / 32 GPUs.\n"
        "# TP=8 PP=4 DP=1, MBS=2 GBS=256 -> GA=128 (same per-replica GA as the 64-GPU TP8 PP4 DP2 GBS512 baseline)\n"
        "# Generated by ~/gb200-661303b8/gen_yamls.py from qwen-72b-r01.yaml\n\n"), t)
    t = sub1(t, "16 nodes, 64 GPUs", "8 nodes, 32 GPUs")
    t = sub1(t, "TP=8  PP=4  CP=1  DP=2", "TP=8  PP=4  CP=1  DP=1")
    t = sub1(t, "MBS=2  GBS=512  GA=128", "MBS=2  GBS=256  GA=128")
    t = sub1(t, "cfg.train.global_batch_size = 512", "cfg.train.global_batch_size = 256", 1)
    t = sub1(t, 'os.getenv("WORLD_SIZE", "64")', 'os.getenv("WORLD_SIZE", "32")', 1)
    return train_common(t)


def gptoss():
    t = (SRC / "gpt-oss-120b-r01.yaml").read_text()
    t = common(t)
    t = sub1(t, "gpt-oss-120b-r01-config", "gptoss-c66-config")
    t = sub1(t, "gpt120b-r01", "gptoss-c66")
    t = re.sub(r"\A(#[^\n]*\n)+\n?", (
        "# GPT-OSS 120B BF16 on cluster 661303b8 (12-node GB200, infra-perf). 8 nodes / 32 GPUs.\n"
        "# EP=32 DP=32, MBS=4 GBS=640 -> GA=5 (same GA as the 64-GPU EP64 GBS1280 baseline)\n"
        "# Generated by ~/gb200-661303b8/gen_yamls.py from gpt-oss-120b-r01.yaml\n\n"), t)
    t = sub1(t, "EP=64  DP=64", "EP=32  DP=32")
    t = sub1(t, "cfg.model.expert_model_parallel_size = 64", "cfg.model.expert_model_parallel_size = 32", 1)
    t = sub1(t, "cfg.train.global_batch_size = 1280", "cfg.train.global_batch_size = 640", 1)
    t = sub1(t, 'os.getenv("WORLD_SIZE", "64")', 'os.getenv("WORLD_SIZE", "32")', 1)
    return train_common(t)


def train_common(t):
    t = sub1(t, "completions: 16", "completions: 8", 1)
    t = sub1(t, "parallelism: 16", "parallelism: 8", 1)
    t = sub1(t, "NNODES=16", "NNODES=8", 1)
    t = re.sub(r'(name: WORLD_SIZE\n\s*value: )"64"', r'\1"32"', t)
    t = t.replace("/ 16 nodes", "/ 8 nodes")
    assert '"64"' not in t, "leftover 64"
    # HF token (secret infra-perf/hf-token) for tokenizer/config downloads.
    # GPT-OSS base already references mpiercy-hf-token -> repoint; Qwen base has none -> add.
    if "mpiercy-hf-token" in t:
        return sub1(t, "name: mpiercy-hf-token", "name: hf-token", 1)
    t = sub1(t, "              - name: CUDA_DEVICE_ORDER\n",
             "              - name: HF_TOKEN\n                valueFrom:\n                  secretKeyRef: {name: hf-token, key: token}\n"
             "              - name: CUDA_DEVICE_ORDER\n", 1)
    return t


if __name__ == "__main__":
    for name, fn in [("nccl-12n-c66.yaml", nccl), ("qwen-72b-c66.yaml", qwen), ("gpt-oss-120b-c66.yaml", gptoss)]:
        (DST / name).write_text(fn())
        print("wrote", DST / name)
